import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from result_analyzer import AnalysisResult, build_answer_prompt, generate_answer

def sample_result():
    return {"status":"success","columns":["city","total_revenue"],"rows":[["Delhi",190000.0]],"row_count":1,"execution_time":0.001,"error":None}

def test_analysis_result_model():
    assert AnalysisResult(answer="Delhi generated the highest revenue.").answer.startswith("Delhi")

def test_prompt_contains_question_and_result():
    prompt = build_answer_prompt("Which city generated the highest revenue?", sample_result())
    assert "Which city generated the highest revenue?" in prompt and "Delhi" in prompt and "190000.0" in prompt

def test_supported_answer_uses_template_without_api_key():
    result = generate_answer("Which city generated the highest revenue?", sample_result())
    assert isinstance(result, AnalysisResult)
    assert "Delhi" in result.answer and "190,000" in result.answer

def test_empty_result_says_no_matching_records():
    result = generate_answer("What was revenue in an unknown city?", {"status":"success","columns":["city","total_revenue"],"rows":[],"row_count":0})
    assert "No matching records" in result.answer

def test_multi_row_answer_lists_values():
    data = {"status":"success","columns":["city","total_revenue"],"rows":[["Delhi",190000.0],["Mumbai",155000.0]],"row_count":2}
    answer = generate_answer("What is the total revenue generated by each city?", data).answer
    assert "Delhi" in answer and "Mumbai" in answer and "190,000" in answer
