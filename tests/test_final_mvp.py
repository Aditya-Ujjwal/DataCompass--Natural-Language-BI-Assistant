def test_top_four_resolves_to_three_actual_database_rows():
    import tempfile
    from sqlalchemy import create_engine, text
    from sql_executor import execute_sql
    intent = parse_question_rules("What are the top 4 cities with highest revenue?")
    query_plan = create_query_plan(intent, SCHEMA)
    sql = build_sql_deterministically(query_plan, SCHEMA)
    engine = create_engine("sqlite:///:memory:")
    with engine.begin() as con:
        con.execute(text("CREATE TABLE sales (id INTEGER, city TEXT, product TEXT, revenue REAL, sale_date TEXT)"))
        con.execute(text("INSERT INTO sales VALUES (1,'Delhi','Laptop',190000,'2026-01-01'), (2,'Mumbai','Phone',155000,'2026-01-02'), (3,'Bangalore','Tablet',80000,'2026-01-03')"))
    result = execute_sql(engine, sql)
    assert result["status"] == "success"
    assert result["row_count"] == 3
    assert result["rows"][0][0] == "Delhi"


