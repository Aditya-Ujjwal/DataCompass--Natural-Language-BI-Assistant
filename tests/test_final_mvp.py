SCHEMA = {"sales": [{"name":"id","type":"INTEGER"},{"name":"city","type":"TEXT"},{"name":"product","type":"TEXT"},{"name":"revenue","type":"REAL"},{"name":"sale_date","type":"TEXT"}]}


def test_all_four_reported_question_shapes():
    q1 = parse_question_rules("Which city generated the highest revenue?")
    q2 = parse_question_rules("What are the top 4 cities with highest revenue?")
    q3 = parse_question_rules("What are the total revenue generated by each city?")
    q4 = parse_question_rules("Show me 10 rows of the dataset")
    assert q1.limit == 1 and q1.sort_order == "descending"
    assert q2.dimension == "city" and q2.limit == 4
    assert q3.metric == "revenue" and q3.dimension == "city"
    assert q4.intent == "lookup" and q4.limit == 10 and q4.metric is None


def test_bar_chart_query_produces_chart_spec():
    result = {"status":"success","columns":["city","total_revenue"],"rows":[["Delhi",190000.0],["Mumbai",155000.0],["Bangalore",80000.0]],"row_count":3}
    spec = suggest_visualization(result)
    assert spec.chart_type == "bar" and spec.x == "city" and spec.y == "total_revenue"


def test_answer_templates_and_grounding():
    result = {"status":"success","columns":["city","total_revenue"],"rows":[["Delhi",190000.0]],"row_count":1}
    answer = generate_answer("Which city generated the highest revenue?", result).answer
    assert "Delhi" in answer and "190,000" in answer
