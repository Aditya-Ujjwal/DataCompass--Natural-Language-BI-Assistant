def test_known_values_uses_database_dialect_identifier_preparer():
    from sqlalchemy import create_engine, text
    from assistant import _known_values

    engine = create_engine("sqlite:///:memory:")
    with engine.begin() as connection:
        connection.execute(text('CREATE TABLE "sales data" ("city name" TEXT, revenue REAL)'))
        connection.execute(text('INSERT INTO "sales data" VALUES (:c1, :r1), (:c2, :r2)'), {'c1': 'Delhi', 'r1': 10, 'c2': 'Mumbai', 'r2': 20})

    schema = {
        "sales data": [
            {"name": "city name", "type": "TEXT"},
            {"name": "revenue", "type": "REAL"},
        ]
    }
    values = _known_values(engine, schema)
    assert set(values["city name"]) == {"Delhi", "Mumbai"}
